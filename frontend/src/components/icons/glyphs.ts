/**
 * The studio's icon vocabulary.
 *
 * One file, one set of names. A call site asks for `orders`, not for a
 * library's `Shirt`, which buys two things: retheming the console's
 * iconography is one edit rather than eighty-two, and two desks cannot pick two
 * different metaphors for the same noun (the old nav had three different glyphs
 * that all meant "list").
 *
 * Icons are SVG, never glyphs. A font character cannot take a stroke weight,
 * align to a text baseline, or carry an accessible name — the console's nav used
 * twenty of them, and the row-menu triggers were emoji with no label at all.
 *
 * Conventions
 * - Sizes follow a scale: 14 for a chip, 16 for nav and buttons (the default),
 *   20 for a tab or section head, 24 for an empty state, 32+ for a hero.
 * - `strokeWidth` defaults to 1.75 because lucide's 2 is heavy at 16px.
 * - An icon is decorative by default (`aria-hidden`). If it is the only content
 *   of a control, the control carries the accessible name, not the icon; if an
 *   icon genuinely needs its own name it takes `aria-label` and becomes a
 *   labelled image.
 */
